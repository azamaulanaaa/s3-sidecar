//! Integration tests for the release scripts.

use std::error::Error;
use std::fs;
use std::path::Path;
use std::process::{Command, Output};

use tempfile::TempDir;

type TestResult = Result<(), Box<dyn Error>>;

/// The fixture crate version before a test changes it.
const OLD_VERSION: &str = "0.2.0";

/// The version of the unrelated package in the fixture lockfile.
const SERDE_VERSION: &str = "1.0.229";

struct Fixture {
    dir: TempDir,
}

impl Fixture {
    /// Create a fixture with the real scripts and a crate at `version`.
    fn new(version: &str) -> Result<Self, Box<dyn Error>> {
        let dir = tempfile::tempdir()?;
        let scripts = dir.path().join("scripts");
        fs::create_dir(&scripts)?;

        let real_scripts = Path::new(env!("CARGO_MANIFEST_DIR")).join("scripts");
        fs::copy(
            real_scripts.join("set-version.sh"),
            scripts.join("set-version.sh"),
        )?;
        fs::copy(
            real_scripts.join("check-release-tag.sh"),
            scripts.join("check-release-tag.sh"),
        )?;

        fs::write(dir.path().join("Cargo.toml"), manifest_text(version))?;
        fs::write(dir.path().join("Cargo.lock"), lockfile_text(version))?;

        Ok(Self { dir })
    }

    /// Run one script with one argument.
    fn run(&self, script: &str, argument: &str) -> Result<Output, Box<dyn Error>> {
        let output = Command::new("bash")
            .arg(self.dir.path().join("scripts").join(script))
            .arg(argument)
            .current_dir(self.dir.path())
            .output()?;
        Ok(output)
    }

    fn read_manifest(&self) -> std::io::Result<String> {
        fs::read_to_string(self.dir.path().join("Cargo.toml"))
    }

    fn read_lockfile(&self) -> std::io::Result<String> {
        fs::read_to_string(self.dir.path().join("Cargo.lock"))
    }
}

fn manifest_text(version: &str) -> String {
    format!(
        r#"[package]
name = "s3-sidecar"
version = "{version}"
edition = "2024"

[dependencies]
serde = "1"
"#
    )
}

fn lockfile_text(version: &str) -> String {
    format!(
        r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "s3-sidecar"
version = "{version}"
dependencies = [
 "serde",
]

[[package]]
name = "serde"
version = "{SERDE_VERSION}"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "4148590afebada386688f18773da617792bf2ef03ffc1e4cbd2b1d45b023e0ba"
"#
    )
}

/// Return the version of the `[package]` section.
fn manifest_version(manifest: &str) -> Option<String> {
    let mut in_package = false;
    for line in manifest.lines() {
        if line.starts_with('[') {
            in_package = line == "[package]";
            continue;
        }
        if !in_package {
            continue;
        }
        if let Some(version) = version_value(line) {
            return Some(version);
        }
    }
    None
}

/// Return the version of one package in a lockfile.
fn lock_version(lockfile: &str, package: &str) -> Option<String> {
    let header = format!("name = \"{package}\"");
    lockfile
        .lines()
        .skip_while(|line| *line != header.as_str())
        .nth(1)
        .and_then(version_value)
}

/// Read a version from a line of the form `version = "x.y.z"`.
fn version_value(line: &str) -> Option<String> {
    line.strip_prefix("version = \"")
        .and_then(|value| value.strip_suffix('"'))
        .map(str::to_owned)
}

fn assert_success(output: &Output) {
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert_eq!(output.status.code(), Some(0), "The script failed: {stderr}");
}

fn assert_exit(output: &Output, code: i32) {
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert_eq!(
        output.status.code(),
        Some(code),
        "The script returned the wrong exit code: {stderr}"
    );
}

fn stdout(output: &Output) -> String {
    String::from_utf8_lossy(&output.stdout).into_owned()
}

#[test]
fn set_version_accepts_release_candidate() -> TestResult {
    let fixture = Fixture::new(OLD_VERSION)?;

    let output = fixture.run("set-version.sh", "0.3.0-rc.1")?;
    assert_success(&output);

    let manifest = fixture.read_manifest()?;
    let lockfile = fixture.read_lockfile()?;

    assert_eq!(
        manifest_version(&manifest).as_deref(),
        Some("0.3.0-rc.1"),
        "The manifest version is wrong."
    );
    assert_eq!(
        lock_version(&lockfile, "s3-sidecar").as_deref(),
        Some("0.3.0-rc.1"),
        "The lock version is wrong."
    );
    Ok(())
}

