#[test]
fn set_version_keeps_unrelated_lock_version() -> TestResult {
    let fixture = Fixture::new(OLD_VERSION)?;

    let output = fixture.run("set-version.sh", "0.3.0-rc.1")?;
    assert_success(&output);

    let lockfile = fixture.read_lockfile()?;

    assert_eq!(
        lock_version(&lockfile, "serde").as_deref(),
        Some(SERDE_VERSION),
        "The unrelated lock version changed."
    );
    Ok(())
}

#[test]
fn set_version_rejects_invalid_version() -> TestResult {
    let fixture = Fixture::new(OLD_VERSION)?;
    let manifest_before = fixture.read_manifest()?;
    let lockfile_before = fixture.read_lockfile()?;

    let output = fixture.run("set-version.sh", "0.3")?;
    assert_exit(&output, 2);

    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        stderr.contains("ERROR"),
        "The script did not report an error."
    );
    assert_eq!(
        fixture.read_manifest()?,
        manifest_before,
        "The manifest changed."
    );
    assert_eq!(
        fixture.read_lockfile()?,
        lockfile_before,
        "The lockfile changed."
    );
    Ok(())
}

#[test]
fn check_tag_accepts_release_candidate() -> TestResult {
    let fixture = Fixture::new("0.3.0-rc.1")?;

    let output = fixture.run("check-release-tag.sh", "v0.3.0-rc.1")?;
    assert_success(&output);

    assert!(
        stdout(&output).contains("The tag matches the crate version."),
        "The script did not confirm the tag."
    );
    Ok(())
}

#[test]
fn check_tag_accepts_tag_forms() -> TestResult {
    let fixture = Fixture::new("0.3.0-rc.1")?;

    for tag in ["0.3.0-rc.1", "s3-sidecar-v0.3.0-rc.1"] {
        let output = fixture.run("check-release-tag.sh", tag)?;
        assert_success(&output);
        assert!(
            stdout(&output).contains("The tag matches the crate version."),
            "The script did not confirm the tag: {tag}"
        );
    }
    Ok(())
}

#[test]
fn check_tag_rejects_mismatch() -> TestResult {
    let fixture = Fixture::new("0.3.0-rc.1")?;

    let output = fixture.run("check-release-tag.sh", "v0.3.0")?;
    assert_exit(&output, 1);

    let text = stdout(&output);
    assert!(
        text.contains("Tag version: 0.3.0"),
        "The tag version is missing."
    );
    assert!(
        text.contains("Crate version: 0.3.0-rc.1"),
        "The crate version is missing."
    );
    Ok(())
}

#[test]
fn check_tag_rejects_invalid_tag() -> TestResult {
    let fixture = Fixture::new("0.3.0-rc.1")?;

    let output = fixture.run("check-release-tag.sh", "v0.3")?;
    assert_exit(&output, 2);

    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        stderr.contains("ERROR"),
        "The script did not report an error."
    );
    Ok(())
}
